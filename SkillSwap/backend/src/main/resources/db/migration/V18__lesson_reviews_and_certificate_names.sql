CREATE TABLE IF NOT EXISTS tb_lesson_reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_id BIGINT NOT NULL REFERENCES tb_lessons(lesson_id) ON DELETE CASCADE,
    reviewer_id UUID NOT NULL REFERENCES tb_users(user_id) ON DELETE CASCADE,
    reviewed_user_id UUID NOT NULL REFERENCES tb_users(user_id) ON DELETE CASCADE,
    stars INTEGER NOT NULL CHECK (stars BETWEEN 1 AND 5),
    comment VARCHAR(1200),
    skill_subject VARCHAR(180) NOT NULL,
    reviewer_full_name VARCHAR(180) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ux_lesson_review_reviewer UNIQUE (lesson_id, reviewer_id)
);
