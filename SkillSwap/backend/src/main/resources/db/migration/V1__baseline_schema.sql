-- Baseline PostgreSQL da plataforma SkillSwap.
-- O esquema substitui o antigo bloco comentado em sintaxe MySQL.

CREATE TABLE IF NOT EXISTS tb_roles (
    role_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS tb_users (
    user_id UUID PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    birth_date DATE,
    phone_number VARCHAR(20),
    verification_code VARCHAR(6),
    verification_code_expiry TIMESTAMP,
    verified BOOLEAN DEFAULT FALSE,
    verified_at TIMESTAMP,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    two_factor_secret VARCHAR(255),
    bio TEXT,
    country VARCHAR(100),
    city VARCHAR(100),
    state VARCHAR(100),
    followers INT DEFAULT 0
    ,verified_badge BOOLEAN DEFAULT FALSE
    ,banned BOOLEAN DEFAULT FALSE
    ,fcm_token VARCHAR(4096)
    ,libras_avatar_enabled BOOLEAN DEFAULT FALSE
    ,preferred_theme VARCHAR(50) DEFAULT 'default'
);

CREATE TABLE IF NOT EXISTS tb_profiles (
    profile_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL UNIQUE,
    description TEXT,
    image_url VARCHAR(255),
    location VARCHAR(255),
    contact_info VARCHAR(255),
    social_media_links TEXT,
    availability_status VARCHAR(50),
    experience_level VARCHAR(255),
    education_level VARCHAR(255),
    interests TEXT,
    is_private BOOLEAN DEFAULT FALSE,
    FOREIGN KEY (user_id) REFERENCES tb_users(user_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS tb_skills (
    skill_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    description TEXT,
    category VARCHAR(255),
    level VARCHAR(50),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    profile_id BIGINT,
    FOREIGN KEY (profile_id) REFERENCES tb_profiles(profile_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS tb_user_roles (
    user_id UUID NOT NULL,
    role_id BIGINT NOT NULL,
    PRIMARY KEY (user_id, role_id),
    FOREIGN KEY (user_id) REFERENCES tb_users(user_id) ON DELETE CASCADE,
    FOREIGN KEY (role_id) REFERENCES tb_roles(role_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS tb_user_skills (
    user_id UUID NOT NULL,
    skill_id BIGINT NOT NULL,
    PRIMARY KEY (user_id, skill_id),
    FOREIGN KEY (user_id) REFERENCES tb_users(user_id) ON DELETE CASCADE,
    FOREIGN KEY (skill_id) REFERENCES tb_skills(skill_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS tb_communities (
    community_id UUID PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    description TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS tb_community_members (
    community_id UUID NOT NULL,
    user_id UUID NOT NULL,
    joined_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (community_id, user_id),
    FOREIGN KEY (community_id) REFERENCES tb_communities(community_id) ON DELETE CASCADE,
    FOREIGN KEY (user_id) REFERENCES tb_users(user_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS tb_posts (
    post_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content TEXT NOT NULL,
    title VARCHAR(255) NOT NULL,
    user_id UUID NOT NULL,
    profile_id BIGINT NOT NULL,
    community_id UUID,
    image_url VARCHAR(255),
    video_url VARCHAR(255),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    likes_count INT DEFAULT 0,
    reposts_count INT DEFAULT 0,
    comments_count INT DEFAULT 0,
    shares_count INT DEFAULT 0,
    views_count INT DEFAULT 0,
    repost_of BIGINT,
    share_url VARCHAR(255),
    FOREIGN KEY (user_id) REFERENCES tb_users(user_id) ON DELETE CASCADE,
    FOREIGN KEY (profile_id) REFERENCES tb_profiles(profile_id) ON DELETE CASCADE,
    FOREIGN KEY (community_id) REFERENCES tb_communities(community_id) ON DELETE CASCADE,
    FOREIGN KEY (repost_of) REFERENCES tb_posts(post_id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS tb_comments (
    comment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id BIGINT NOT NULL,
    user_id UUID NOT NULL,
    content TEXT NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (post_id) REFERENCES tb_posts(post_id) ON DELETE CASCADE,
    FOREIGN KEY (user_id) REFERENCES tb_users(user_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS tb_likes (
    post_id BIGINT NOT NULL,
    user_id UUID NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (post_id, user_id),
    FOREIGN KEY (post_id) REFERENCES tb_posts(post_id) ON DELETE CASCADE,
    FOREIGN KEY (user_id) REFERENCES tb_users(user_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS tb_reposts (
    post_id BIGINT NOT NULL,
    user_id UUID NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (post_id, user_id),
    FOREIGN KEY (post_id) REFERENCES tb_posts(post_id) ON DELETE CASCADE,
    FOREIGN KEY (user_id) REFERENCES tb_users(user_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS tb_share_links (
    share_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id BIGINT NOT NULL,
    user_id UUID NOT NULL,
    share_url VARCHAR(255) NOT NULL UNIQUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    click_count INT DEFAULT 0,
    FOREIGN KEY (post_id) REFERENCES tb_posts(post_id) ON DELETE CASCADE,
    FOREIGN KEY (user_id) REFERENCES tb_users(user_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS tb_lessons (
    lesson_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_id UUID NOT NULL,
    student_id UUID NOT NULL,
    scheduled_time TIMESTAMP WITH TIME ZONE,
    status VARCHAR(50),
    FOREIGN KEY (teacher_id) REFERENCES tb_users(user_id) ON DELETE CASCADE,
    FOREIGN KEY (student_id) REFERENCES tb_users(user_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS tb_notifications (
    notification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL,
    message TEXT NOT NULL,
    sent_at TIMESTAMP NOT NULL,
    read BOOLEAN DEFAULT FALSE,
    FOREIGN KEY (user_id) REFERENCES tb_users(user_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS tb_messages (
    message_id UUID PRIMARY KEY,
    sender_id UUID NOT NULL,
    receiver_id UUID NOT NULL,
    content TEXT NOT NULL,
    type VARCHAR(50) NOT NULL CHECK (type IN ('text', 'image', 'video', 'pdf')),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (sender_id) REFERENCES tb_users(user_id) ON DELETE CASCADE,
    FOREIGN KEY (receiver_id) REFERENCES tb_users(user_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS tb_skill_swap_proposals (
    proposal_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id UUID NOT NULL,
    receiver_id UUID NOT NULL,
    offered_skill_id BIGINT NOT NULL,
    requested_skill_id BIGINT NOT NULL,
    status VARCHAR(50) NOT NULL CHECK (status IN ('PENDING', 'ACCEPTED', 'REJECTED', 'BLOCKED')),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (sender_id) REFERENCES tb_users(user_id) ON DELETE CASCADE,
    FOREIGN KEY (receiver_id) REFERENCES tb_users(user_id) ON DELETE CASCADE,
    FOREIGN KEY (offered_skill_id) REFERENCES tb_skills(skill_id) ON DELETE CASCADE,
    FOREIGN KEY (requested_skill_id) REFERENCES tb_skills(skill_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS tb_permissions (
    permission_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL,
    permission_type VARCHAR(50) NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('ALLOWED', 'ALLOWED_DURING_USE', 'DENIED', 'NOT_SET')),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES tb_users(user_id) ON DELETE CASCADE,
    UNIQUE (user_id, permission_type)
);

CREATE TABLE IF NOT EXISTS tb_access_logs (
    access_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL,
    access_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    ip_address VARCHAR(45),
    location VARCHAR(255),
    city VARCHAR(100),
    subdivision VARCHAR(100),
    country VARCHAR(100),
    FOREIGN KEY (user_id) REFERENCES tb_users(user_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS tb_two_factor_configs (
    config_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL,
    method VARCHAR(50) NOT NULL CHECK (method IN ('GOOGLE_AUTH', 'EMAIL', 'SMS')),
    enabled BOOLEAN DEFAULT FALSE,
    secret VARCHAR(255),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES tb_users(user_id) ON DELETE CASCADE,
    UNIQUE (user_id, method)
);

CREATE TABLE IF NOT EXISTS tb_user_following (
    user_id UUID NOT NULL,
    following_id UUID NOT NULL,
    PRIMARY KEY (user_id, following_id),
    FOREIGN KEY (user_id) REFERENCES tb_users(user_id) ON DELETE CASCADE,
    FOREIGN KEY (following_id) REFERENCES tb_users(user_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS tb_user_communities (
    user_id UUID NOT NULL,
    community_id UUID NOT NULL,
    PRIMARY KEY (user_id, community_id),
    FOREIGN KEY (user_id) REFERENCES tb_users(user_id) ON DELETE CASCADE,
    FOREIGN KEY (community_id) REFERENCES tb_communities(community_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS tb_user_messages (
    user_id UUID NOT NULL,
    message_id UUID NOT NULL,
    PRIMARY KEY (user_id, message_id),
    FOREIGN KEY (user_id) REFERENCES tb_users(user_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS tb_achievements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    achievement_key VARCHAR(255) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    description VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS tb_user_achievements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL,
    achievement_id BIGINT NOT NULL,
    image_url VARCHAR(1024) NOT NULL,
    custom_prompt VARCHAR(500),
    unlocked_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES tb_users(user_id) ON DELETE CASCADE,
    FOREIGN KEY (achievement_id) REFERENCES tb_achievements(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS tb_bans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL,
    ip_address VARCHAR(255),
    reason VARCHAR(255) NOT NULL,
    banned_by UUID,
    expires_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    FOREIGN KEY (user_id) REFERENCES tb_users(user_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS tb_chat_messages (
    message_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id UUID,
    receiver_id UUID,
    content TEXT,
    voice_data BYTEA,
    file_data BYTEA,
    file_type VARCHAR(255),
    sent_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (sender_id) REFERENCES tb_users(user_id) ON DELETE SET NULL,
    FOREIGN KEY (receiver_id) REFERENCES tb_users(user_id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS tb_ratings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rated_user_id UUID NOT NULL,
    rater_user_id UUID NOT NULL,
    proposal_id BIGINT NOT NULL UNIQUE,
    stars INT NOT NULL CHECK (stars BETWEEN 1 AND 5),
    comment VARCHAR(500),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (rated_user_id) REFERENCES tb_users(user_id) ON DELETE CASCADE,
    FOREIGN KEY (rater_user_id) REFERENCES tb_users(user_id) ON DELETE CASCADE,
    FOREIGN KEY (proposal_id) REFERENCES tb_skill_swap_proposals(proposal_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS tb_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_user_id UUID NOT NULL,
    reported_user_id UUID NOT NULL,
    reason VARCHAR(1000),
    status VARCHAR(32) NOT NULL DEFAULT 'PENDING',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (reporter_user_id) REFERENCES tb_users(user_id) ON DELETE CASCADE,
    FOREIGN KEY (reported_user_id) REFERENCES tb_users(user_id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_access_logs_user_id ON tb_access_logs(user_id);
CREATE INDEX IF NOT EXISTS idx_permissions_user_id ON tb_permissions(user_id);
CREATE INDEX IF NOT EXISTS idx_users_email ON tb_users(email);
CREATE INDEX IF NOT EXISTS idx_posts_user_id ON tb_posts(user_id);
CREATE INDEX IF NOT EXISTS idx_posts_community_id ON tb_posts(community_id);
CREATE INDEX IF NOT EXISTS idx_comments_post_id ON tb_comments(post_id);
CREATE INDEX IF NOT EXISTS idx_likes_post_id ON tb_likes(post_id);
CREATE INDEX IF NOT EXISTS idx_reposts_post_id ON tb_reposts(post_id);
CREATE INDEX IF NOT EXISTS idx_share_links_post_id ON tb_share_links(post_id);
CREATE INDEX IF NOT EXISTS idx_two_factor_configs_user_id ON tb_two_factor_configs(user_id);
CREATE INDEX IF NOT EXISTS idx_messages_sender_id ON tb_messages(sender_id);
CREATE INDEX IF NOT EXISTS idx_messages_receiver_id ON tb_messages(receiver_id);
