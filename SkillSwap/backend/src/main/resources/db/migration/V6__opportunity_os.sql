-- Jornada fechada: plano de evolução, evidência prática e candidatura.
CREATE TABLE IF NOT EXISTS ss_growth_plans (
    plan_id UUID PRIMARY KEY,
    owner_id UUID NOT NULL,
    goal VARCHAR(240) NOT NULL,
    target_role VARCHAR(160),
    constraints TEXT,
    weekly_hours INT NOT NULL CHECK (weekly_hours BETWEEN 1 AND 40),
    status VARCHAR(24) NOT NULL CHECK (status IN ('ACTIVE', 'COMPLETED', 'ARCHIVED')),
    progress_percent INT NOT NULL DEFAULT 0 CHECK (progress_percent BETWEEN 0 AND 100),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_growth_plan_owner FOREIGN KEY (owner_id) REFERENCES tb_users(user_id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_growth_plans_owner_updated ON ss_growth_plans (owner_id, updated_at DESC);

CREATE TABLE IF NOT EXISTS ss_growth_plan_steps (
    step_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id UUID NOT NULL,
    step_order INT NOT NULL,
    title VARCHAR(160) NOT NULL,
    description TEXT NOT NULL,
    kind VARCHAR(32) NOT NULL,
    skill_focus VARCHAR(160),
    estimated_hours INT NOT NULL CHECK (estimated_hours > 0),
    status VARCHAR(24) NOT NULL CHECK (status IN ('TODO', 'IN_PROGRESS', 'DONE')),
    evidence_id UUID,
    CONSTRAINT fk_growth_step_plan FOREIGN KEY (plan_id) REFERENCES ss_growth_plans(plan_id) ON DELETE CASCADE,
    CONSTRAINT uk_growth_step_order UNIQUE (plan_id, step_order)
);

CREATE TABLE IF NOT EXISTS ss_skill_evidence (
    evidence_id UUID PRIMARY KEY,
    owner_id UUID NOT NULL,
    opportunity_id UUID,
    plan_step_id BIGINT,
    title VARCHAR(180) NOT NULL,
    skill_focus VARCHAR(160) NOT NULL,
    description TEXT NOT NULL,
    artifact_url VARCHAR(1000),
    evidence_type VARCHAR(32) NOT NULL,
    verification_status VARCHAR(32) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_skill_evidence_owner FOREIGN KEY (owner_id) REFERENCES tb_users(user_id) ON DELETE CASCADE,
    CONSTRAINT fk_skill_evidence_opportunity FOREIGN KEY (opportunity_id) REFERENCES tb_access_opportunities(opportunity_id) ON DELETE SET NULL,
    CONSTRAINT fk_skill_evidence_step FOREIGN KEY (plan_step_id) REFERENCES ss_growth_plan_steps(step_id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_skill_evidence_owner_created ON ss_skill_evidence (owner_id, created_at DESC);

CREATE TABLE IF NOT EXISTS ss_opportunity_applications (
    application_id UUID PRIMARY KEY,
    applicant_id UUID NOT NULL,
    opportunity_id UUID NOT NULL,
    status VARCHAR(24) NOT NULL CHECK (status IN ('SUBMITTED', 'IN_REVIEW', 'ACCEPTED', 'DECLINED', 'WITHDRAWN')),
    message TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_opportunity_application UNIQUE (applicant_id, opportunity_id),
    CONSTRAINT fk_opportunity_application_user FOREIGN KEY (applicant_id) REFERENCES tb_users(user_id) ON DELETE CASCADE,
    CONSTRAINT fk_opportunity_application_opportunity FOREIGN KEY (opportunity_id) REFERENCES tb_access_opportunities(opportunity_id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_opportunity_applications_user_created ON ss_opportunity_applications (applicant_id, created_at DESC);
